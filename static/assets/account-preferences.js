const accountLanguageKey = 'disc-tools:account:language';
const accountTimeZoneKey = 'disc-tools:account:time-zone';

function getAccountPreference(key) {
    try {
        return localStorage.getItem(key);
    } catch {
        return null;
    }
}

function accountLanguage() {
    return getAccountPreference(accountLanguageKey) === 'de' ? 'de' : 'en';
}

function accountText(source, values = {}) {
    const text = accountLanguage() === 'de' && Object.hasOwn(accountGerman, source)
        ? accountGerman[source] : source;
    return text.replace(/\{(\w+)\}/g, (placeholder, name) => values[name] ?? placeholder);
}

function accountDateTimeFormat() {
    return new Intl.DateTimeFormat(accountLanguage(), {
        dateStyle: 'medium', timeStyle: 'short',
        timeZone: getAccountPreference(accountTimeZoneKey) === 'UTC' ? 'UTC' : undefined
    });
}

(() => {
    document.documentElement.lang = accountLanguage();
    document.title = document.title.replace(/^(.+?) \| /, (_, title) => accountText(title) + ' | ');
    for (const node of document.querySelectorAll('[data-account-text]')) {
        node.textContent = accountText(node.textContent);
    }
    for (const node of document.querySelectorAll('[data-account-aria]')) {
        node.setAttribute('aria-label', accountText(node.getAttribute('aria-label')));
    }

    const form = document.getElementById('account-preferences');
    if (!form) return;
    const language = form.elements.namedItem('language');
    const timeZone = form.elements.namedItem('timeZone');
    const status = document.getElementById('preferences-status');
    language.value = accountLanguage();
    timeZone.value = getAccountPreference(accountTimeZoneKey) === 'UTC' ? 'UTC' : 'local';

    form.addEventListener('submit', event => {
        event.preventDefault();
        const previousLanguage = accountLanguage();
        try {
            localStorage.setItem(accountTimeZoneKey, timeZone.value === 'UTC' ? 'UTC' : 'local');
            localStorage.setItem(accountLanguageKey, language.value === 'de' ? 'de' : 'en');
            if (accountLanguage() !== previousLanguage) {
                window.location.reload();
                return;
            }
            status.textContent = accountText('Preferences saved.');
        } catch {
            status.textContent = accountText('Could not save these preferences in your browser.');
        }
    });
})();
